def test_un_canal_comun_cambia_al_topic_aunque_no_tenga_lista(api, monkeypatch):
    """El Topic se encuentra buscando, y su lista de subidas no existe: antes
    eso impedía el cambio de canal, que exigía la lista."""
    falsa = api(n=20)
    otro = "UC" + "o" * 22

    def api_get(endpoint, params, key, intentos=3):
        if endpoint == "channels" and params.get("forHandle"):
            canal = {
                "id": otro,
                "snippet": {"title": "Los del Ejemplo"},
                "contentDetails": {"relatedPlaylists": {"uploads": "UU" + otro[2:]}},
            }
            return {"items": [canal]}
        if endpoint == "channels":
            # Lo que contesta hoy un Topic: sin el campo de la lista.
            return {"items": [{"id": CANAL, "snippet": {"title": "Los del Ejemplo - Topic"}}]}
        if endpoint == "search" and params.get("type") == "channel":
            return {"items": [{"snippet": {"channelId": CANAL, "channelTitle": "Los del Ejemplo - Topic"}}]}
        return falsa(endpoint, params, key)

    monkeypatch.setattr(R, "api_get", api_get)
    res = R.relevar("https://www.youtube.com/@losdelejemplo", "k", with_codes=False)
    assert res["via_topic"] is True
    assert res["channel_id"] == CANAL, "se busca en el Topic, no en el canal que se pegó"
    assert res["via"] == "busqueda" and len(res["tracks"]) == 20
    busquedas = [p for e, p in falsa.llamadas if e == "search"]
    assert busquedas and all(p["channelId"] == CANAL for p in busquedas)


