"""Cómo se lista un canal. Sin red y sin clave.

Existe por una rotura concreta. Entre fines de septiembre y noviembre de 2026
YouTube dejó de publicar la lista de subidas de los canales Topic:
`channels.list` informa `videoCount: 0` y la lista contesta 404, aunque los
temas siguen estando. Como la app sólo sabía listar por ahí, relevar un canal
Topic, que es lo único que la app sabe relevar, fallaba en el primer paso con
el error crudo de Google. Los 807 tests de entonces pasaban, porque ninguno
habla con YouTube y los grabados son de cuando la lista existía.

Lo que se fija acá:

  - si la lista de subidas no está, el canal se lista por el buscador
  - si está, se usa la lista, que cuesta cien veces menos
  - el buscador se pagina, no repite y sigue más allá de su tope de ~500
  - si la cuota se acaba en el medio, no se tira lo ya listado
  - los lanzamientos sin la línea «Provided to YouTube by» no se descartan
  - las unidades de cuota se cuentan, pedido por pedido

Las respuestas imitan la forma real de la API, tal como contestaba el
16/11/2026 para el canal Topic con que se encontró el problema.
"""

import io
import json
import urllib.error
from typing import Any, override

import pytest

from migrador import productos as P
from migrador import relevar_core as R
from migrador.contratos import Relevamiento

CANAL = "UC" + "t" * 22
SUBIDAS = "UU" + CANAL[2:]
URL = f"https://www.youtube.com/channel/{CANAL}"

DESC_CON = (
    "Provided to YouTube by Top Media\n\n{t} · Los del Ejemplo\n\nLlora, Llora Corazón\n\n"
    "℗ Clan Music\n\nReleased on: 1998-01-01\n\nAuto-generated by YouTube."
)
# La forma real de las entregas viejas: sin la primera línea, todo corrido un lugar.
DESC_SIN = (
    "{t} · Los del Ejemplo\n\nPasajeros de una Nostalgia\n\n℗ 1992 Alex Producciones\n\n"
    "Released on: 2019-03-22\n\nComposer: Fulano\n\nAuto-generated by YouTube."
)
DESC_A_MANO = "Mirá nuestro nuevo video.\n\nSeguinos en las redes."


class FalsaAPI:
    """Doble de `relevar_core.api_get` con la conducta de noviembre de 2026."""

    def __init__(self, n=5, sin_subidas=True, cuota_en_pagina=None, desc=None, total=None):
        # `cuota_en_pagina=4`: la cuarta búsqueda es la que se queda sin cuota.
        self.n = n
        self.sin_subidas = sin_subidas
        self.cuota_en_pagina = cuota_en_pagina
        self.desc = desc or (lambda i: DESC_CON)
        self.total = n if total is None else total
        self.llamadas = []

    def ids(self):
        return [f"v{i:09d}x" for i in range(self.n)]

    def fecha(self, i):
        # El más nuevo primero y un video por minuto: el orden de `order=date`.
        m = self.n - i
        return f"2025-01-{1 + m // 1440:02d}T{(m // 60) % 24:02d}:{m % 60:02d}:00Z"

    def cuantas(self, endpoint):
        return sum(1 for e, _ in self.llamadas if e == endpoint)

    def __call__(self, endpoint, params, key, intentos=3):
        self.llamadas.append((endpoint, dict(params)))
        if endpoint == "channels":
            canal = {
                "id": CANAL,
                "snippet": {"title": "Los del Ejemplo - Topic"},
                "contentDetails": {"relatedPlaylists": {"uploads": SUBIDAS}},
            }
            return {"items": [canal]}
        if endpoint == "playlistItems":
            if self.sin_subidas:
                raise R.RelevarError("la lista no existe", "sin_lista")
            R.CUOTA.sumar(endpoint)
            return {
                "items": [{"contentDetails": {"videoId": v}} for v in self.ids()],
                "pageInfo": {"totalResults": self.n},
            }
        if endpoint == "search":
            if self.cuota_en_pagina and self.cuantas("search") >= self.cuota_en_pagina:
                raise R.RelevarError("se acabó la cuota", "cuota")
            R.CUOTA.sumar(endpoint)
            todos = list(enumerate(self.ids()))
            antes = params.get("publishedBefore")
            if antes:  # inclusivo, como el de verdad
                todos = [(i, v) for i, v in todos if self.fecha(i) <= antes]
            todos = todos[:500]  # el tope real del buscador
            desde = int(params.get("pageToken") or 0)
            out: dict[str, Any] = {
                "items": [
                    {"id": {"kind": "youtube#video", "videoId": v}, "snippet": {"publishedAt": self.fecha(i)}}
                    for i, v in todos[desde : desde + 50]
                ],
                "pageInfo": {"totalResults": self.total},
            }
            if desde + 50 < len(todos):
                out["nextPageToken"] = str(desde + 50)
            return out
        if endpoint == "videos":
            R.CUOTA.sumar(endpoint)
            items = []
            for v in params["id"].split(","):
                i = int(v[1:10])
                items.append(
                    {
                        "id": v,
                        "snippet": {
                            "title": f"Tema {i}",
                            "description": self.desc(i).format(t=f"Tema {i}"),
                            "publishedAt": "2025-02-04T10:00:00Z",
                        },
                        "statistics": {"viewCount": "10"},
                        "contentDetails": {"duration": "PT3M20S"},
                    }
                )
            return {"items": items}
        raise AssertionError(f"pedido inesperado: {endpoint}")


