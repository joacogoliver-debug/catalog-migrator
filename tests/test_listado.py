def _respuesta(cuerpo):
    """Lo que devuelve `urlopen`: algo que se abre con `with` y se lee."""
    return io.BytesIO(json.dumps(cuerpo).encode())


def test_cada_pedido_suma_lo_que_cuesta(monkeypatch):
    monkeypatch.setattr(R.urllib.request, "urlopen", lambda req, timeout=30: _respuesta({"items": []}))
    R.CUOTA.empezar()
    R.api_get("channels", {}, "k")
    R.api_get("videos", {}, "k")
    R.api_get("search", {}, "k")
    assert R.CUOTA.n == 102, "el buscador cuesta cien; lo demás, una"


def test_la_lista_que_no_existe_tiene_su_codigo(monkeypatch):
    """Es lo que contesta YouTube hoy por la lista de subidas de un Topic. Del
    código depende que `relevar` siga por el buscador en vez de mostrar el error."""
    cuerpo = json.dumps(
        {
            "error": {
                "code": 404,
                "message": "The playlist identified with the request's playlistId parameter cannot be found.",
                "errors": [{"domain": "youtube.playlistItem", "reason": "playlistNotFound"}],
            }
        }
    )

    def urlopen(req, timeout=30):
        raise urllib.error.HTTPError(req.full_url, 404, "Not Found", None, io.BytesIO(cuerpo.encode()))  # type: ignore[arg-type]

    monkeypatch.setattr(R.urllib.request, "urlopen", urlopen)
    R.CUOTA.empezar()
    with pytest.raises(R.RelevarError) as e:
        R.api_get("playlistItems", {"playlistId": SUBIDAS}, "k")
    assert e.value.codigo == "sin_lista"
    assert "playlist" not in str(e.value).lower(), "nada en inglés, por si llegara a mostrarse"
    assert R.CUOTA.n == 0, "un pedido rechazado no se cuenta como gastado"


